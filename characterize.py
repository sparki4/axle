"""axle characterize: record what adopted functions actually do today, as tests.

For every function in `.axle/axle.map.json` that AXLE can call safely, this runs a small
set of inputs through the real code (Python, JavaScript or C, via the generated bindings)
and writes `characterization.test.axl`: one test per function asserting the observed
results.  It records behavior; it does not claim the behavior is correct.  Run `axle test`
on the file before and after a rewrite or a migration to see exactly what changed.
Inputs that make the real code fail are listed as `aborts` and get no assertion.
"""
import itertools
import json
import pathlib
import subprocess
import sys
import tempfile

import axle

VALUES = {'i64': ['0', '1', '-1', '2', '7', '100', '1000'], 'u64': ['0u64', '1u64', '2u64', '7u64', '100u64', '1000u64'],
          'bool': ['false', 'true'], 'f64': ['0.0', '1.0', '-1.5', '2.5', '100.0']}
MAX_CASES = 12


def cases_for(params):
    pools = []
    for p in params:
        pool = VALUES.get(p['type'])
        if pool is None:
            return None
        pools.append(pool)
    if not pools:
        return [()]
    combos = list(itertools.product(*pools))
    if len(combos) <= MAX_CASES:
        return combos
    step = len(combos) / MAX_CASES
    return [combos[int(i * step)] for i in range(MAX_CASES)]


def literal(kind, text):
    if kind == 'bool':
        return 'true' if text.strip() in {'true', 'True', '1'} else 'false'
    if kind == 'f64':
        return text.strip() if text.strip().replace('.', '', 1).lstrip('-').isdigit() else None
    if kind == 'u64':
        return text.strip() + 'u64'
    return text.strip()


def run(root, out_dir=None, link_search=(), link_arg=()):
    root = pathlib.Path(root).resolve()
    out_dir = pathlib.Path(out_dir).resolve() if out_dir else root / '.axle'
    map_path = out_dir / 'axle.map.json'
    if not map_path.exists():
        raise axle.Error('no axle.map.json found', hint=f'run `axle adopt {root}` first')
    report = json.loads(map_path.read_text(encoding='utf-8'))
    targets, skipped = [], []
    for entry in report['bindings']:
        name = entry['name']
        if entry.get('call') != 'safe' or entry.get('status') != 'bound':
            skipped.append(dict(name=name, reason='needs unsafe or a link step, or is not directly callable'))
            continue
        if entry['result'] not in {'i64', 'u64', 'bool', 'f64'}:
            skipped.append(dict(name=name, reason=f'result type {entry["result"]} cannot be recorded'))
            continue
        cases = cases_for(entry['params'])
        if cases is None:
            skipped.append(dict(name=name, reason='a parameter type has no sample values'))
            continue
        targets.append((entry, cases))
    if not targets:
        raise axle.Error('nothing to characterize', hint='adopt found no safe functions with i64, u64 or bool signatures')
    bindings = out_dir / 'bindings.axl'
    probe_lines = [f'import "{bindings.name}";', '', 'fn main() -> unit ![io] {', '    let which = arg_u64(1u64);']
    index = []
    for entry, cases in targets:
        for case in cases:
            call = f'{entry["name"]}({", ".join(case)})'
            probe_lines.append(f'    if which == {len(index)}u64 {{ print({call}); }}')
            index.append((entry, case))
    probe_lines.append('}')
    probe = out_dir / '_characterize_probe.axl'
    probe.write_text('\n'.join(probe_lines) + '\n', encoding='utf-8')
    observed = {}
    aborts = []
    try:
        rust = axle.compile_file(probe)
        with tempfile.TemporaryDirectory(prefix='axle-char-') as directory:
            exe = axle.build(rust, pathlib.Path(directory) / ('probe.exe' if sys.platform == 'win32' else 'probe'), 'release', link_search, link_arg)
            for number, (entry, case) in enumerate(index):
                process = subprocess.run([str(exe), str(number)], capture_output=True, text=True, timeout=60)
                key = (entry['name'], case)
                if process.returncode == 0 and process.stdout.strip():
                    observed[key] = process.stdout.strip().splitlines()[-1]
                else:
                    aborts.append(dict(function=entry['name'], inputs=list(case), detail=(process.stderr.strip().splitlines() or ['no output'])[0][:200]))
    finally:
        probe.unlink(missing_ok=True)
    out = ['// Generated by `axle characterize`. This records what the code does today, not what it should do.',
           '// Run `axle test` on this file before and after a change; a failing assert is a behavior change.',
           f'import "{bindings.name}";', '']
    recorded = 0
    for entry, cases in targets:
        asserts = []
        for case in cases:
            value = observed.get((entry['name'], case))
            if value is None:
                continue
            expected = literal(entry['result'], value)
            if expected is None:
                continue     # NaN and infinities have no literal
            asserts.append(f'    assert({entry["name"]}({", ".join(case)}) == {expected});')
        if not asserts:
            continue
        recorded += len(asserts)
        out += [f'fn test_{entry["name"]}_behavior() -> unit ![io] {{'] + asserts + ['}', '']
    path = out_dir / 'characterization.test.axl'
    path.write_text('\n'.join(out), encoding='utf-8')
    summary = dict(tool='axle characterize', tests_file=str(path), functions=len(targets), recorded_assertions=recorded,
                   aborts=aborts, skipped=skipped,
                   note='Records current behavior only. A recorded value may itself be a bug.')
    (out_dir / 'characterization.json').write_text(json.dumps(summary, indent=2) + '\n', encoding='utf-8')
    return summary
