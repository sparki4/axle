def build_manifest(parser_choices=None):
    precedence = {}
    for op, level in axle.Parser.PRECEDENCE.items():
        precedence.setdefault(level, []).append(op)
    return {
        'language': 'AXLE', 'version': axle.VERSION, 'edition': axle.EDITION,
        'source_of_truth': 'Generated by the compiler (`axle manifest`). If this disagrees with your memory of AXLE, this is right.',
        'types': {
            'i64': 'signed 64-bit', 'u64': 'unsigned 64-bit', 'bool': 'true/false', 'unit': 'no value (results only)',
            'buf_u64': 'shared checked buffer of u64', '*i64 / *u64 / *bool': 'raw pointers (unsafe to use)',
            'c_int c_uint c_long c_ulong c_size': 'C ABI widths, legal only in extern "c" signatures; seen as i64/u64 by AXLE code'},
        'keywords': sorted(axle.RESERVED - axle.TYPES - set(axle.ABI_TYPES)),
        'effects': ['io', 'mem'], 'guarantees': ['nothrow', 'noalloc'],
        'operators_low_to_high_precedence': [sorted(ops) for _, ops in sorted(precedence.items())] + [['unary: ! - ~']],
        'declarations': ['fn name(p: T, ...) -> T ![effects] nothrow noalloc { ... }', 'import "relative/path.axl";', 'edition "0.4";',
                         'extern "c" fn name(p: T) -> T ![effects] = "symbol";', 'extern "py:file.py[@root]" fn name(p: i64) -> i64;',
                         'extern "js:file.js[@root]" fn name(p: i64) -> i64;', 'native "file.c";', 'link "m";'],
        'statements': ['let x = e;', 'var x: T = e;', 'x = e;', 'if c { } else if c { } else { }', 'while c { }', 'break;', 'continue;',
                       'return e;', 'unsafe { }', 'e;  (e must be unit)'],
        'builtins': [dict(name=n, signature=sig, effects=eff, summary=text, example=example)
                     for n, (sig, eff, text, example) in BUILTIN_DOCS.items()],
        'semantics': SEMANTICS,
        'diagnostic_codes': {code: dict(title=t, cause=c, fix=f) for code, (t, c, f, _, _) in CODES.items()},
        'not_in_axle': {name: hint for name, hint in {**axle.FOREIGN_KEYWORDS, **axle.IDIOMS}.items()},
        'commands': {name: dict(usage=u, purpose=p) for name, (u, p) in COMMANDS.items()},
    }


def render_manifest(m):
    out = [f'# {m["language"]} {m["version"]} (edition {m["edition"]})', '', m['source_of_truth'], '', '## Semantics']
    out += [f'- {line}' for line in m['semantics']]
    out += ['', '## Declarations'] + [f'- `{d}`' for d in m['declarations']]
    out += ['', '## Statements'] + [f'- `{d}`' for d in m['statements']]
    out += ['', '## Builtins']
    for b in m['builtins']:
        eff = f' ![{", ".join(b["effects"])}]' if b['effects'] else ''
        out.append(f'- `{b["signature"]}`{eff}: {b["summary"]}')
    out += ['', '## Commands'] + [f'- `{v["usage"]}`: {v["purpose"]}' for v in m['commands'].values()]
    out += ['', '## Diagnostic codes (axle explain CODE)'] + [f'- {c}: {v["title"]}' for c, v in m['diagnostic_codes'].items()]
    return '\n'.join(out)


def explain(code):
    code = code.upper()
    if code not in CODES:
        raise axle.Error('unknown diagnostic code ' + code, hint='codes: ' + ', '.join(CODES), suggestion=axle.did_you_mean(code, CODES))
    title, cause, fix, bad, good = CODES[code]
    return '\n'.join([f'{code}: {title}', '', f'Cause: {cause}', f'Fix:   {fix}', '', 'Failing example:', '    ' + bad, '', 'Corrected:', '    ' + good])


def run(command, options):
    if command == 'manifest':
        m = build_manifest()
        print(json.dumps(m, indent=2) if options.json else render_manifest(m))
    else:
        print(explain(str(options.source)))
    return 0
